namespace Voyara.Application.DTOs;

/// <summary>
/// Payload to create a new conversational AI session.
/// </summary>
/// <param name="Language">Optional ISO language code (e.g. "en", "ar").</param>
public sealed record CreateConversationRequest(string? Language);

/// <summary>
/// Payload to send a user message to the AI assistant.
/// </summary>
/// <param name="Content">The user's conversational prompt.</param>
public sealed record SendMessageRequest(string Content);

/// <summary>
/// Read model representing a single conversational turn.
/// </summary>
/// <param name="Id">Unique message identifier.</param>
/// <param name="Role">Author role (User, Assistant, System).</param>
/// <param name="Content">Textual content payload.</param>
/// <param name="TokensUsed">Tokens consumed by this turn.</param>
/// <param name="CreatedAt">Message timestamp in UTC.</param>
public sealed record MessageResponse(
    long Id,
    string Role,
    string Content,
    int TokensUsed,
    DateTime CreatedAt);

/// <summary>
/// Summary read model of a conversation session for listing views.
/// </summary>
/// <param name="Id">Conversation identifier.</param>
/// <param name="Language">Interaction language.</param>
/// <param name="State">Current conversation workflow state.</param>
/// <param name="StartedAt">Session start time in UTC.</param>
/// <param name="MessageCount">Total messages exchanged.</param>
/// <param name="JourneyId">Associated journey identifier, if generated.</param>
public sealed record ConversationSummaryResponse(
    Guid Id,
    string Language,
    string State,
    DateTime StartedAt,
    int MessageCount,
    Guid? JourneyId);

/// <summary>
/// Detailed read model representing an AI conversation session and its complete message history.
/// </summary>
/// <param name="Id">Conversation identifier.</param>
/// <param name="Language">Interaction language.</param>
/// <param name="State">Current conversation workflow state.</param>
/// <param name="StartedAt">Session start time in UTC.</param>
/// <param name="JourneyId">Associated journey identifier, if generated.</param>
/// <param name="Messages">Ordered message history.</param>
public sealed record ConversationDetailResponse(
    Guid Id,
    string Language,
    string State,
    DateTime StartedAt,
    Guid? JourneyId,
    IReadOnlyList<MessageResponse> Messages);

/// <summary>
/// Payload to request conversational travel recommendations within an AI session.
/// </summary>
/// <param name="Prompt">Optional tourist prompt or inquiry.</param>
/// <param name="CityId">Optional city filter.</param>
/// <param name="CategoryId">Optional category filter.</param>
/// <param name="Limit">Maximum number of recommendation items to return (default: 3).</param>
public sealed record RequestRecommendationPromptRequest(
    string? Prompt,
    Guid? CityId,
    Guid? CategoryId,
    int Limit = 3);

/// <summary>
/// Structured catalog destination recommended by the AI assistant with explainability reason.
/// </summary>
/// <param name="DestinationId">Unique destination identifier.</param>
/// <param name="Name">Localized destination name.</param>
/// <param name="Description">Localized destination description.</param>
/// <param name="CoverImageUrl">Cover image URL, if available.</param>
/// <param name="Rating">Average visitor rating (0..5).</param>
/// <param name="ReviewCount">Total number of reviews.</param>
/// <param name="Reason">AI explainability rationale.</param>
public sealed record ConversationalRecommendationItem(
    Guid DestinationId,
    string Name,
    string? Description,
    string? CoverImageUrl,
    double Rating,
    int ReviewCount,
    string Reason);

/// <summary>
/// Response payload containing the AI conversational pitch along with structured recommendation items.
/// </summary>
/// <param name="ConversationId">Conversation session identifier.</param>
/// <param name="AssistantMessage">Conversational response text generated by the local LLM.</param>
/// <param name="Recommendations">Structured recommendation cards.</param>
public sealed record ConversationalRecommendationResponse(
    Guid ConversationId,
    string AssistantMessage,
    IReadOnlyList<ConversationalRecommendationItem> Recommendations);

/// <summary>
/// Read model representing extracted tourist trip requirements.
/// </summary>
/// <param name="Country">Destination country.</param>
/// <param name="DurationDays">Planned duration in days.</param>
/// <param name="Interests">Interests and activity preferences.</param>
/// <param name="BudgetAmount">Budget amount.</param>
/// <param name="BudgetCurrency">Budget currency code (e.g. USD).</param>
/// <param name="TravelStyle">Travel tempo and style.</param>
/// <param name="TransportPreference">Transportation mode preference.</param>
/// <param name="IsComplete">Whether all essential requirements are captured.</param>
public sealed record TripRequirementsDto(
    string Country,
    int DurationDays,
    IReadOnlyList<string> Interests,
    decimal BudgetAmount,
    string BudgetCurrency,
    string TravelStyle,
    string TransportPreference,
    bool IsComplete);

/// <summary>
/// Payload to update or apply extracted travel requirements to an ongoing conversation.
/// </summary>
/// <param name="Country">Destination country.</param>
/// <param name="DurationDays">Planned duration in days.</param>
/// <param name="Interests">Interests and activity preferences.</param>
/// <param name="BudgetAmount">Budget amount.</param>
/// <param name="BudgetCurrency">Budget currency code (e.g. USD).</param>
/// <param name="TravelStyle">Travel tempo and style.</param>
/// <param name="TransportPreference">Transportation mode preference.</param>
public sealed record UpdateRequirementsRequest(
    string Country,
    int DurationDays,
    List<string>? Interests,
    decimal BudgetAmount,
    string BudgetCurrency,
    string? TravelStyle,
    string? TransportPreference);

/// <summary>
/// Lightweight catalog destination summary injected into AI assistant context.
/// </summary>
/// <param name="DestinationId">Destination identifier.</param>
/// <param name="Name">Localized destination name.</param>
/// <param name="Description">Localized destination description.</param>
/// <param name="Rating">Average visitor rating (0..5).</param>
/// <param name="ReviewCount">Total review count.</param>
/// <param name="EstimatedVisitMinutes">Typical visit duration in minutes.</param>
public sealed record CatalogContextDestinationDto(
    Guid DestinationId,
    string Name,
    string? Description,
    double Rating,
    int ReviewCount,
    int EstimatedVisitMinutes);

/// <summary>
/// Assembled AI planning context combining conversation state, extracted requirements, and catalog destinations.
/// </summary>
/// <param name="ConversationId">Conversation identifier.</param>
/// <param name="Language">Conversation language code.</param>
/// <param name="State">Current conversation workflow state.</param>
/// <param name="Requirements">Captured trip requirements, if any.</param>
/// <param name="CatalogDestinations">Relevant published catalog destinations.</param>
public sealed record AiConversationContextDto(
    Guid ConversationId,
    string Language,
    string State,
    TripRequirementsDto? Requirements,
    IReadOnlyList<CatalogContextDestinationDto> CatalogDestinations);
