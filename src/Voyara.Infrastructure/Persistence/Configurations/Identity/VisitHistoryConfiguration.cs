using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Identity;

namespace Voyara.Infrastructure.Persistence.Configurations.Identity
{

    /// <summary>
    /// Represents the configuration for the VisitHistory entity type.
    /// The relationship with TouristProfile is configured in TouristProfileConfiguration.
    /// </summary>
    public sealed class VisitHistoryConfiguration : IEntityTypeConfiguration<VisitHistory>
    {
        /// <summary>
        /// Configures the VisitHistory entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the VisitHistory entity type.</param>
        public void Configure(EntityTypeBuilder<VisitHistory> builder)
        {
            // Configures the VisitHistory entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the VisitedOn property.
            builder.Property(x => x.VisitedOn)
                .IsRequired();

            // Configures the TouristProfileId property.
            builder.Property(x => x.TouristProfileId)
                .IsRequired();

            // Configures the DestinationId property.
            builder.Property(x => x.DestinationId)
                .IsRequired();

            // Configures the Destination relationship (a destination that was visited cannot be hard-deleted).
            builder.HasOne(x => x.Destination)
                .WithMany()
                .HasForeignKey(x => x.DestinationId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Restrict);

            // Supports loading the visits of a profile in order.
            builder.HasIndex(x => new
            {
                x.TouristProfileId,
                x.VisitedOn
            });

            // Supports finding who visited a destination.
            builder.HasIndex(x => x.DestinationId);
        }
    }
}
