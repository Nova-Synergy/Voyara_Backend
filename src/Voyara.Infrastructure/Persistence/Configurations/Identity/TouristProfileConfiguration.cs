using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Identity;

namespace Voyara.Infrastructure.Persistence.Configurations.Identity
{

    /// <summary>
    /// Represents the configuration for the TouristProfile entity type.
    /// It is a one-to-one with User and composes the visit history.
    /// </summary>
    public sealed class TouristProfileConfiguration : IEntityTypeConfiguration<TouristProfile>
    {
        /// <summary>
        /// Configures the TouristProfile entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the TouristProfile entity type.</param>
        public void Configure(EntityTypeBuilder<TouristProfile> builder)
        {
            // Configures the TouristProfile entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the UserId property.
            builder.Property(x => x.UserId)
                .IsRequired();

            // Configures the NationalityCode property (ISO 3166-1 alpha-2, stored upper-case).
            builder.Property(x => x.NationalityCode)
                .IsRequired()
                .HasMaxLength(2)
                .IsFixedLength();

            // Configures the PreferredLanguage property (for example en, ar or pt-br, stored lower-case).
            builder.Property(x => x.PreferredLanguage)
                .IsRequired()
                .HasMaxLength(10);

            // Configures the Budget property (the BudgetLevel enum is stored as text).
            builder.Property(x => x.Budget)
                .HasConversion<string>()
                .HasMaxLength(20)
                .IsRequired();

            // Configures the PhotoUrl property.
            builder.Property(x => x.PhotoUrl)
                .IsRequired(false)
                .HasMaxLength(2048);

            // Configures the User relationship (one profile per user; the profile cannot outlive its user).
            builder.HasOne(x => x.User)
                .WithOne(x => x.TouristProfile)
                .HasForeignKey<TouristProfile>(x => x.UserId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            // Configures the Interests relationship (many-to-many through tourist_profile_interests;
            // Interest has no back navigation).
            builder.HasMany(x => x.Interests)
                .WithMany()
                .UsingEntity(join => join.ToTable("tourist_profile_interests"));

            builder.Navigation(x => x.Interests)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Configures the VisitHistories relationship (the visit history belongs to the profile).
            builder.HasMany(x => x.VisitHistories)
                .WithOne(x => x.TouristProfile)
                .HasForeignKey(x => x.TouristProfileId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.VisitHistories)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Guarantees one profile per user.
            builder.HasIndex(x => x.UserId)
                .IsUnique();
        }
    }
}
