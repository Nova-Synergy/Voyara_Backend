using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Identity;

namespace Voyara.Infrastructure.Persistence.Configurations.Identity
{

    /// <summary>
    /// Represents the configuration for the User entity type.
    /// Roles are mapped as a many-to-many relationship and refresh tokens are owned by the user.
    /// The one-to-one relationship with TouristProfile is configured in TouristProfileConfiguration.
    /// </summary>
    public sealed class UserConfiguration : IEntityTypeConfiguration<User>
    {
        /// <summary>
        /// Configures the User entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the User entity type.</param>
        public void Configure(EntityTypeBuilder<User> builder)
        {
            // Configures the User entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the FullName property.
            builder.Property(x => x.FullName)
                .IsRequired()
                .HasMaxLength(200);

            // Configures the Email property (stored normalized: trimmed and lower-case).
            builder.Property(x => x.Email)
                .IsRequired()
                .HasMaxLength(254);

            // Configures the PasswordHash property.
            builder.Property(x => x.PasswordHash)
                .IsRequired()
                .HasMaxLength(500);

            // Configures the EmailConfirmed property.
            builder.Property(x => x.EmailConfirmed)
                .IsRequired();

            // Configures the IsActive property.
            builder.Property(x => x.IsActive)
                .IsRequired();

            // Configures the IsDeleted property.
            builder.Property(x => x.IsDeleted)
                .IsRequired();

            // Configures the CreatedBy property.
            builder.Property(x => x.CreatedBy)
                .IsRequired(false)
                .HasMaxLength(100);

            // Configures the UpdatedBy property.
            builder.Property(x => x.UpdatedBy)
                .IsRequired(false)
                .HasMaxLength(100);

            // Configures the Roles relationship (many-to-many through user_roles; Role has no back navigation).
            builder.HasMany(x => x.Roles)
                .WithMany()
                .UsingEntity(join => join.ToTable("user_roles"));

            builder.Navigation(x => x.Roles)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Configures the RefreshTokens relationship (refresh tokens live and die with their user).
            builder.HasMany(x => x.RefreshTokens)
                .WithOne(x => x.User)
                .HasForeignKey(x => x.UserId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.RefreshTokens)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Hides soft-deleted users from every query.
            builder.HasQueryFilter(x => !x.IsDeleted);

            // Guarantees that e-mail addresses are unique.
            builder.HasIndex(x => x.Email)
                .IsUnique();
        }
    }
}
