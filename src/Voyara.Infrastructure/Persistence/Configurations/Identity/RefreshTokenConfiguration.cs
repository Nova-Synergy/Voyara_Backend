using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Identity;

namespace Voyara.Infrastructure.Persistence.Configurations.Identity
{

    /// <summary>
    /// Represents the configuration for the RefreshToken entity type.
    /// The relationship with User is configured in UserConfiguration.
    /// </summary>
    public sealed class RefreshTokenConfiguration : IEntityTypeConfiguration<RefreshToken>
    {
        /// <summary>
        /// Configures the RefreshToken entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the RefreshToken entity type.</param>
        public void Configure(EntityTypeBuilder<RefreshToken> builder)
        {
            // Configures the RefreshToken entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the TokenHash property (only the hash is stored, never the raw token).
            builder.Property(x => x.TokenHash)
                .IsRequired()
                .HasMaxLength(256);

            // Configures the ExpiresAt property.
            builder.Property(x => x.ExpiresAt)
                .IsRequired();

            // Configures the RevokedAt property.
            builder.Property(x => x.RevokedAt)
                .IsRequired(false);

            // Configures the UserId property.
            builder.Property(x => x.UserId)
                .IsRequired();

            // Supports looking up a token when it is exchanged for a new access token.
            builder.HasIndex(x => x.TokenHash)
                .IsUnique();

            // Supports loading all the tokens of a user.
            builder.HasIndex(x => x.UserId);
        }
    }
}
