using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Identity;

namespace Voyara.Infrastructure.Persistence.Configurations.Identity
{
    /// <summary>
    /// Configuration for the Role entity type.
    /// The many-to-many relationship with User is configured in UserConfiguration.
    /// </summary>
    public sealed class RoleConfiguration : IEntityTypeConfiguration<Role>
    {
        /// <summary>
        /// Configures the entity type for the Role model using the specified builder.
        /// </summary>
        /// <remarks>This method sets up primary keys, property constraints, relationships, and indexes for the
        /// Role entity. It is typically called by the Entity Framework infrastructure when building the
        /// model.</remarks>
        /// <param name="builder">The builder used to configure the Role entity type and its properties.</param>
        public void Configure(EntityTypeBuilder<Role> builder)
        {
            // Configure the table name and the primary key for the Role entity.
            builder.ToTable("roles");
            builder.HasKey(r => r.Id);

            // The key is an integer generated by the database.
            builder.Property(r => r.Id).ValueGeneratedOnAdd();

            // Configure the Name property for the Role entity.
            builder.Property(r => r.Name).HasMaxLength(50).IsRequired();

            // Role names are unique.
            builder.HasIndex(r => r.Name).IsUnique();
        }
    }
}
