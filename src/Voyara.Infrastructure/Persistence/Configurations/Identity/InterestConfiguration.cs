using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Identity;

namespace Voyara.Infrastructure.Persistence.Configurations.Identity
{
    /// <summary>
    /// Configuration for the Interest entity type.
    /// The many-to-many relationship with TouristProfile is configured in TouristProfileConfiguration.
    /// </summary>
    public sealed class InterestConfiguration : IEntityTypeConfiguration<Interest>
    {
        /// <summary>
        /// Configures the entity type for the Interest model using the specified builder.
        /// </summary>
        /// <remarks>This method sets up primary keys, property constraints, relationships, and indexes for the
        /// Interest entity. It is typically called by the Entity Framework infrastructure when building the
        /// model.</remarks>
        /// <param name="builder">The builder used to configure the Interest entity type and its properties.</param>
        public void Configure(EntityTypeBuilder<Interest> builder)
        {
            // Configure the table name and the primary key for the Interest entity.
            builder.ToTable("interests");
            builder.HasKey(i => i.Id);

            // The key is an integer generated by the database.
            builder.Property(i => i.Id).ValueGeneratedOnAdd();

            // Configure the Code property for the Interest entity.
            builder.Property(i => i.Code).HasMaxLength(50).IsRequired();

            // Interest codes are unique.
            builder.HasIndex(i => i.Code).IsUnique();
        }
    }
}
