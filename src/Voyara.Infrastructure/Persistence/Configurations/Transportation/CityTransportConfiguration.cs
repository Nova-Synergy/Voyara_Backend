using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Transportation;

namespace Voyara.Infrastructure.Persistence.Configurations.Transportation;

/// <summary>
/// Mapping for the CityTransport aggregate root. Its parts are owned by the aggregate and are mapped in their
/// own configuration classes: <see cref="TransportRouteConfiguration"/>, <see cref="StationConfiguration"/>
/// and <see cref="DestinationTransportConfiguration"/>.
/// </summary>
public sealed class CityTransportConfiguration : IEntityTypeConfiguration<CityTransport>
{
    /// <inheritdoc />
    public void Configure(EntityTypeBuilder<CityTransport> builder)
    {
        builder.ToTable("city_transports");
        builder.HasKey(c => c.Id);

        // The identifier is generated by BaseEntity, so EF must never generate or infer it.
        builder.Property(c => c.Id).ValueGeneratedNever();

        builder.Property(c => c.CityId).IsRequired();
        builder.Property(c => c.TransportTypeId).IsRequired();
        builder.Property(c => c.Description).HasMaxLength(CityTransport.MaxTextLength).IsRequired();
        builder.Property(c => c.ApproxCost).HasPrecision(18, 2).IsRequired();
        builder.Property(c => c.Currency).HasMaxLength(CityTransport.CurrencyCodeLength).IsRequired();
        builder.Property(c => c.OperatingHours).HasMaxLength(CityTransport.MaxOperatingHoursLength).IsRequired();
        builder.Property(c => c.SafetyInfo).HasMaxLength(CityTransport.MaxTextLength).IsRequired();

        builder.HasQueryFilter(c => !c.IsDeleted);

        // Reference to the TransportType aggregate by Id (foreign key, no navigation property).
        builder.HasOne<TransportType>()
            .WithMany()
            .HasForeignKey(c => c.TransportTypeId)
            .OnDelete(DeleteBehavior.Restrict);

        // One entry per city and transport type. Soft-deleted rows do not block a new entry.
        builder.HasIndex(c => new { c.CityId, c.TransportTypeId })
            .IsUnique()
            .HasFilter("\"IsDeleted\" = false");

        // Parts of the aggregate, each mapped in its own configuration class.
        builder.OwnsMany(c => c.Routes, TransportRouteConfiguration.Configure);
        builder.OwnsMany(c => c.Destinations, DestinationTransportConfiguration.Configure);

        // The aggregate exposes read-only collections backed by private lists.
        builder.Navigation(c => c.Routes).UsePropertyAccessMode(PropertyAccessMode.Field);
        builder.Navigation(c => c.Destinations).UsePropertyAccessMode(PropertyAccessMode.Field);
    }
}
