using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Culture_Rules;

namespace Voyara.Infrastructure.Persistence.Configurations.Culture_Rules;

/// <summary>
/// Mapping for the LocalRule aggregate root. Its scope and translations are owned by the aggregate and are
/// mapped in their own configuration classes: <see cref="RuleScopeConfiguration"/> and
/// <see cref="LocalRuleTranslationConfiguration"/>.
/// </summary>
public sealed class LocalRuleConfiguration : IEntityTypeConfiguration<LocalRule>
{
    /// <inheritdoc />
    public void Configure(EntityTypeBuilder<LocalRule> builder)
    {
        builder.ToTable("local_rules");
        builder.HasKey(r => r.Id);

        // The identifier is generated by BaseEntity, so EF must never generate or infer it.
        builder.Property(r => r.Id).ValueGeneratedNever();

        // Stored as text so the table stays readable and survives reordering of enum members.
        builder.Property(r => r.Type)
            .HasConversion<string>()
            .HasMaxLength(30)
            .IsRequired();

        builder.Property(r => r.IsOfficial).IsRequired();
        builder.Property(r => r.Source).HasMaxLength(LocalRule.MaxSourceLength).IsRequired();
        builder.Property(r => r.LastReviewedAt).IsRequired();

        builder.HasQueryFilter(r => !r.IsDeleted);

        // Parts of the aggregate, each mapped in its own configuration class.
        builder.OwnsOne(r => r.Scope, RuleScopeConfiguration.Configure);
        builder.Navigation(r => r.Scope).IsRequired();

        builder.OwnsMany(r => r.Translations, LocalRuleTranslationConfiguration.Configure);

        // The aggregate exposes a read-only collection backed by a private list.
        builder.Navigation(r => r.Translations).UsePropertyAccessMode(PropertyAccessMode.Field);
    }
}
