using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Moderation;
using Voyara.Domain.ValueObjects;

namespace Voyara.Infrastructure.Persistence.Configurations.Moderation;

/// <summary>
/// Configures the append-only moderation audit log for Entity Framework Core persistence.</summary>
/// <remarks>
/// <para>
/// This configuration establishes the database schema for the AuditLog entity, which serves as
/// the immutable audit trail for all admin actions and report resolutions. Every entry is
/// created once and never changed, with a sequential long identifier generated by the database.</para>
/// <para>
/// The design deliberately avoids the platform's base audit class to ensure append-only semantics;
/// soft-delete flags and updated timestamps would contradict this requirement. Instead, AuditLog
/// uses a database-generated long identifier and stores target information as text to support
/// any kind of object in any module.</para>
/// <list type="bullet">
/// <item>
/// <description>
/// Table mapping to "moderation_audit_logs" with required properties for ActorId, Action,
/// TargetType, TargetId, and Timestamp.</description>
/// </item>
/// <item>
/// <description>
/// Value-generated long identifier (Id) to uniquely identify each audit entry.</description>
/// </item>
/// <item>
/// <description>
/// Required constraint on ActorId, referencing the Identity module.</description>
/// </item>
/// <item>
/// <description>
/// Required constraints on Action, TargetType, and TargetId with maximum length limits.</description>
/// </item>
/// <item>
/// <description>
/// Required constraint on Timestamp (UTC) to record when the action happened.</description>
/// </item>
/// <item>
/// <description>
/// JSON string storage for AuditDetails with validation and type safety using jsonb PostGIS type.</description>
/// </item>
/// <item>
/// <description>
/// Indexes on ActorId, Timestamp, and the (TargetType, TargetId) pair for efficient querying.</description>
/// </item>
/// </list>
/// </remarks>
public sealed class AuditLogConfiguration
    : IEntityTypeConfiguration<AuditLog>
{
    /// <summary>
    /// Configures the AuditLog entity type for the database context.</summary>
    /// <remarks>
    /// <para>
    /// This method is called during DbContext model creation to establish the complete mapping
    /// for the append-only audit log, including the value object AuditDetails stored as JSON.</para>
    /// <para>
    /// The design ensures every admin action and report resolution is written to this trail,
    /// providing accountability without the need for soft-delete flags or updated timestamps.</para>
    /// <list type="bullet">
    /// <item>
    /// <description>
    /// Primary key on the Id property, generated by the database.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Required constraint on ActorId, establishing the identity of the admin who performed the action.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Required constraint on Action with maximum length of 100 characters.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Required constraint on TargetType with maximum length of 50 characters.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Required constraint on TargetId with maximum length of 50 characters.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Required constraint on Timestamp (UTC) to record when the action happened.</description>
    /// </item>
    /// <item>
    /// <description>
    /// JSON string storage for AuditDetails with validation and type safety using jsonb PostGIS type.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Index on ActorId for efficient retrieval of all actions by an admin.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Index on Timestamp for chronological queries of audit entries.</description>
    /// </item>
    /// <item>
    /// <description>
    /// Composite index on (TargetType, TargetId) to optimize queries filtering by target object.</description>
    /// </item>
    /// </list>
    /// </remarks>
    /// <param name="builder">The entity type builder used to configure the AuditLog entity.</param>
    public void Configure(EntityTypeBuilder<AuditLog> builder)
    {
        builder.ToTable("moderation_audit_logs");

        builder.HasKey(log => log.Id);

        // The database generates the sequential long identifier.
        builder.Property(log => log.Id)
            .ValueGeneratedOnAdd();

        builder.Property(log => log.ActorId)
            .IsRequired();

        builder.Property(log => log.Action)
            .HasMaxLength(AuditLog.MaxActionLength)
            .IsRequired();

        builder.Property(log => log.TargetType)
            .HasMaxLength(AuditLog.MaxTargetTypeLength)
            .IsRequired();

        builder.Property(log => log.TargetId)
            .HasMaxLength(AuditLog.MaxTargetIdLength)
            .IsRequired();

        builder.Property(log => log.Timestamp)
            .IsRequired();

        // Store AuditDetails as its validated JSON string.
        builder.Property(log => log.Details)
            .HasConversion(
                details => details.Json,
                json => AuditDetails.Create(json).Value)
            .HasColumnName("details_json")
            .HasColumnType("jsonb")
            .IsRequired();

        builder.HasIndex(log => log.ActorId);

        builder.HasIndex(log => log.Timestamp);

        builder.HasIndex(log => new
        {
            log.TargetType,
            log.TargetId
        });
    }
}
