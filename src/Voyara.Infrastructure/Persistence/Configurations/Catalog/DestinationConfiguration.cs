using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NetTopologySuite.Geometries;
using Voyara.Domain.Entities.Catalog;
using Voyara.Domain.ValueObjects;

namespace Voyara.Infrastructure.Persistence.Configurations.Catalog
{

    /// <summary>
    /// Represents the configuration for the Destination aggregate root.
    /// Its gallery, opening hours, opening exceptions, ticket prices and translations are composed by the destination.
    /// </summary>
    public sealed class DestinationConfiguration : IEntityTypeConfiguration<Destination>
    {
        /// <summary>
        /// Configures the Destination entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the Destination entity type.</param>
        public void Configure(EntityTypeBuilder<Destination> builder)
        {
            // Configures the Destination entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the Location property (GeoPoint is stored as a PostGIS point, SRID 4326).
            builder.Property(x => x.Location)
                .HasConversion(
                    geoPoint => new Point(geoPoint.Longitude, geoPoint.Latitude) { SRID = 4326 },
                    point => GeoPoint.Create(point.Y, point.X).Value)
                .HasColumnType("geometry(Point,4326)")
                .IsRequired();

            // Configures the EstimatedVisitMinutes property (1 to 1440 minutes).
            builder.Property(x => x.EstimatedVisitMinutes)
                .IsRequired();

            // Configures the AverageRating property (0 to 5).
            builder.Property(x => x.AverageRating)
                .HasPrecision(3, 2)
                .IsRequired();

            // Configures the ReviewCount property.
            builder.Property(x => x.ReviewCount)
                .IsRequired();

            // Configures the PopularityScore property.
            builder.Property(x => x.PopularityScore)
                .IsRequired();

            // Configures the Status property (the DestinationStatus enum is stored as text).
            builder.Property(x => x.Status)
                .HasConversion<string>()
                .HasMaxLength(20)
                .IsRequired();

            // Configures the CityId property.
            builder.Property(x => x.CityId)
                .IsRequired();

            // Configures the CategoryId property.
            builder.Property(x => x.CategoryId)
                .IsRequired();

            // Configures the IsDeleted property.
            builder.Property(x => x.IsDeleted)
                .IsRequired();

            // Configures the CreatedBy property.
            builder.Property(x => x.CreatedBy)
                .IsRequired(false)
                .HasMaxLength(100);

            // Configures the UpdatedBy property.
            builder.Property(x => x.UpdatedBy)
                .IsRequired(false)
                .HasMaxLength(100);

            // Configures optimistic concurrency through the PostgreSQL xmin system column.
            builder.Property<uint>("xmin")
                .IsRowVersion();

            // Domain events are raised in memory and published through the outbox; they are never mapped.
            builder.Ignore(x => x.DomainEvents);

            // Configures the City relationship (a city that has destinations cannot be hard-deleted).
            builder.HasOne(x => x.City)
                .WithMany()
                .HasForeignKey(x => x.CityId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Restrict);

            // Configures the Category relationship (a category that has destinations cannot be hard-deleted).
            builder.HasOne(x => x.Category)
                .WithMany()
                .HasForeignKey(x => x.CategoryId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Restrict);

            // Configures the Images relationship.
            builder.HasMany(x => x.Images)
                .WithOne(x => x.Destination)
                .HasForeignKey(x => x.DestinationId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.Images)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Configures the OpeningHours relationship.
            builder.HasMany(x => x.OpeningHours)
                .WithOne(x => x.Destination)
                .HasForeignKey(x => x.DestinationId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.OpeningHours)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Configures the OpeningExceptions relationship.
            builder.HasMany(x => x.OpeningExceptions)
                .WithOne(x => x.Destination)
                .HasForeignKey(x => x.DestinationId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.OpeningExceptions)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Configures the TicketPrices relationship.
            builder.HasMany(x => x.TicketPrices)
                .WithOne(x => x.Destination)
                .HasForeignKey(x => x.DestinationId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.TicketPrices)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Configures the Translations relationship.
            builder.HasMany(x => x.Translations)
                .WithOne(x => x.Destination)
                .HasForeignKey(x => x.DestinationId)
                .IsRequired()
                .OnDelete(DeleteBehavior.Cascade);

            builder.Navigation(x => x.Translations)
                .UsePropertyAccessMode(PropertyAccessMode.Field);

            // Hides soft-deleted destinations from every query.
            builder.HasQueryFilter(x => !x.IsDeleted);

            // Supports filtering destinations by status.
            builder.HasIndex(x => x.Status);

            // Supports browsing the destinations of a city by status.
            builder.HasIndex(x => new
            {
                x.CityId,
                x.Status
            });

            // Supports browsing the destinations of a category.
            builder.HasIndex(x => x.CategoryId);

            // Supports spatial (nearby) queries.
            builder.HasIndex(x => x.Location)
                .HasMethod("gist");
        }
    }
}
