using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Catalog;

namespace Voyara.Infrastructure.Persistence.Configurations.Catalog
{

    /// <summary>
    /// Represents the configuration for the Category entity type.
    /// The relationship with Destination is configured in DestinationConfiguration.
    /// </summary>
    public sealed class CategoryConfiguration : IEntityTypeConfiguration<Category>
    {
        /// <summary>
        /// Configures the Category entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the Category entity type.</param>
        public void Configure(EntityTypeBuilder<Category> builder)
        {
            // Configures the Category entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the Code property.
            builder.Property(x => x.Code)
                .IsRequired()
                .HasMaxLength(50);

            // Configures the Icon property.
            builder.Property(x => x.Icon)
                .IsRequired()
                .HasMaxLength(200);

            // Configures the IsActive property.
            builder.Property(x => x.IsActive)
                .IsRequired();

            // Guarantees that category codes are unique.
            builder.HasIndex(x => x.Code)
                .IsUnique();
        }
    }
}
