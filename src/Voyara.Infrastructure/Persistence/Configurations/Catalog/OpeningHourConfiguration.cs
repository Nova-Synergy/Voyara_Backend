using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Catalog;

namespace Voyara.Infrastructure.Persistence.Configurations.Catalog
{

    /// <summary>
    /// Represents the configuration for the OpeningHour entity type.
    /// The relationship with Destination is configured in DestinationConfiguration.
    /// </summary>
    public sealed class OpeningHourConfiguration : IEntityTypeConfiguration<OpeningHour>
    {
        /// <summary>
        /// Configures the OpeningHour entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the OpeningHour entity type.</param>
        public void Configure(EntityTypeBuilder<OpeningHour> builder)
        {
            // Configures the OpeningHour entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the Day property (the DayOfWeek enum is stored as a small number).
            builder.Property(x => x.Day)
                .HasConversion<short>()
                .IsRequired();

            // Configures the OpensAt property (time of day).
            builder.Property(x => x.OpensAt)
                .HasColumnType("time")
                .IsRequired();

            // Configures the ClosesAt property (time of day).
            builder.Property(x => x.ClosesAt)
                .HasColumnType("time")
                .IsRequired();

            // Configures the IsClosed property.
            builder.Property(x => x.IsClosed)
                .IsRequired();

            // Configures the DestinationId property.
            builder.Property(x => x.DestinationId)
                .IsRequired();

            // Guarantees one set of opening hours per destination and day.
            builder.HasIndex(x => new
            {
                x.DestinationId,
                x.Day
            })
                .IsUnique();
        }
    }
}
