using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Catalog;

namespace Voyara.Infrastructure.Persistence.Configurations.Catalog
{

    /// <summary>
    /// Represents the configuration for the OpeningException entity type.
    /// The relationship with Destination is configured in DestinationConfiguration.
    /// </summary>
    public sealed class OpeningExceptionConfiguration : IEntityTypeConfiguration<OpeningException>
    {
        /// <summary>
        /// Configures the OpeningException entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the OpeningException entity type.</param>
        public void Configure(EntityTypeBuilder<OpeningException> builder)
        {
            // Configures the OpeningException entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the Date property.
            builder.Property(x => x.Date)
                .HasColumnType("date")
                .IsRequired();

            // Configures the IsClosed property.
            builder.Property(x => x.IsClosed)
                .IsRequired();

            // Configures the Reason property.
            builder.Property(x => x.Reason)
                .IsRequired()
                .HasMaxLength(500);

            // Configures the DestinationId property.
            builder.Property(x => x.DestinationId)
                .IsRequired();

            // Guarantees one opening exception per destination and date.
            builder.HasIndex(x => new
            {
                x.DestinationId,
                x.Date
            })
                .IsUnique();
        }
    }
}
