using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Catalog;

namespace Voyara.Infrastructure.Persistence.Configurations.Catalog
{

    /// <summary>
    /// Represents the configuration for the TicketPrice entity type.
    /// The relationship with Destination is configured in DestinationConfiguration.
    /// </summary>
    public sealed class TicketPriceConfiguration : IEntityTypeConfiguration<TicketPrice>
    {
        /// <summary>
        /// Configures the TicketPrice entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the TicketPrice entity type.</param>
        public void Configure(EntityTypeBuilder<TicketPrice> builder)
        {
            // Configures the TicketPrice entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the VisitorType property (the VisitorType enum is stored as text).
            builder.Property(x => x.VisitorType)
                .HasConversion<string>()
                .HasMaxLength(20)
                .IsRequired();

            // Configures the Price value object (stored in the same table as PriceAmount and PriceCurrency).
            builder.OwnsOne(x => x.Price, price =>
            {
                price.Property(x => x.Amount)
                    .HasColumnName("PriceAmount")
                    .HasPrecision(18, 2)
                    .IsRequired();

                price.Property(x => x.Currency)
                    .HasColumnName("PriceCurrency")
                    .HasMaxLength(3)
                    .IsFixedLength()
                    .IsRequired();
            });

            builder.Navigation(x => x.Price)
                .IsRequired();

            // Configures the Notes property.
            builder.Property(x => x.Notes)
                .IsRequired()
                .HasMaxLength(500);

            // Configures the DestinationId property.
            builder.Property(x => x.DestinationId)
                .IsRequired();

            // Guarantees one ticket price per destination and visitor type.
            builder.HasIndex(x => new
            {
                x.DestinationId,
                x.VisitorType
            })
                .IsUnique();
        }
    }
}
