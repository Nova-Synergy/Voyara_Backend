using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Voyara.Domain.Entities.Catalog;

namespace Voyara.Infrastructure.Persistence.Configurations.Catalog
{

    /// <summary>
    /// Represents the configuration for the DestinationImage entity type.
    /// The relationship with Destination is configured in DestinationConfiguration.
    /// </summary>
    public sealed class DestinationImageConfiguration : IEntityTypeConfiguration<DestinationImage>
    {
        /// <summary>
        /// Configures the DestinationImage entity type.
        /// </summary>
        /// <param name="builder">The builder used to configure the DestinationImage entity type.</param>
        public void Configure(EntityTypeBuilder<DestinationImage> builder)
        {
            // Configures the DestinationImage entity.
            builder.HasKey(x => x.Id);

            // Configures the Id property (generated by the domain, never by the database).
            builder.Property(x => x.Id)
                .ValueGeneratedNever();

            // Configures the Url property.
            builder.Property(x => x.Url)
                .IsRequired()
                .HasMaxLength(2048);

            // Configures the SortOrder property.
            builder.Property(x => x.SortOrder)
                .IsRequired();

            // Configures the IsCover property.
            builder.Property(x => x.IsCover)
                .IsRequired();

            // Configures the DestinationId property.
            builder.Property(x => x.DestinationId)
                .IsRequired();

            // Supports loading the gallery of a destination in order.
            builder.HasIndex(x => new
            {
                x.DestinationId,
                x.SortOrder
            });
        }
    }
}
