using System.Net.Http.Json;
using System.Text.Json.Serialization;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using Voyara.Application.Abstractions;

namespace Voyara.Infrastructure.Ai;

/// <summary>
/// AI provider connecting to a local Ollama instance running Qwen (e.g. qwen3.5:4b).
/// </summary>
public sealed class OllamaAiProvider : IAiProvider
{
    private readonly HttpClient _httpClient;
    private readonly AiOptions _options;
    private readonly ILogger<OllamaAiProvider> _logger;

    /// <summary>
    /// Initializes a new instance of <see cref="OllamaAiProvider"/>.
    /// </summary>
    public OllamaAiProvider(
        HttpClient httpClient,
        IOptions<AiOptions> options,
        ILogger<OllamaAiProvider> logger)
    {
        _httpClient = httpClient;
        _options = options.Value;
        _logger = logger;

        if (!string.IsNullOrWhiteSpace(_options.OllamaBaseUrl))
        {
            _httpClient.BaseAddress = new Uri(_options.OllamaBaseUrl);
        }

        _httpClient.Timeout = TimeSpan.FromSeconds(Math.Max(30, _options.TimeoutSeconds));
    }

    /// <inheritdoc />
    public async Task<string> GetCompletionAsync(string prompt, CancellationToken cancellationToken = default)
    {
        try
        {
            var modelName = string.IsNullOrWhiteSpace(_options.Model) ? "qwen3.5:4b" : _options.Model.Trim();
            var request = new OllamaGenerateRequest
            {
                Model = modelName,
                Prompt = prompt,
                Stream = false
            };

            var response = await _httpClient.PostAsJsonAsync("/api/generate", request, cancellationToken);
            response.EnsureSuccessStatusCode();

            var result = await response.Content.ReadFromJsonAsync<OllamaGenerateResponse>(cancellationToken: cancellationToken);
            if (!string.IsNullOrWhiteSpace(result?.Response))
            {
                return result.Response.Trim();
            }

            _logger.LogWarning("Ollama returned an empty response for model {Model}", modelName);
            return "No response generated by the local AI assistant.";
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to get AI completion from local Ollama instance at {BaseUrl}", _options.OllamaBaseUrl);
            return "The AI assistant is temporarily unavailable. Please verify that Ollama is running locally.";
        }
    }

    private sealed class OllamaGenerateRequest
    {
        [JsonPropertyName("model")]
        public string Model { get; set; } = string.Empty;

        [JsonPropertyName("prompt")]
        public string Prompt { get; set; } = string.Empty;

        [JsonPropertyName("stream")]
        public bool Stream { get; set; } = false;
    }

    private sealed class OllamaGenerateResponse
    {
        [JsonPropertyName("model")]
        public string? Model { get; set; }

        [JsonPropertyName("response")]
        public string? Response { get; set; }

        [JsonPropertyName("done")]
        public bool Done { get; set; }
    }
}
