using Voyara.Domain.Entities.CostEstimation;
using Voyara.Domain.Enums;
using Voyara.Domain.ValueObjects;
using Voyara.SharedKernel.Entities;

namespace Voyara.Domain.Entities.TripAndJourney;

/// <summary>
/// Aggregate root representing an end-to-end travel itinerary composed of sequential daily itineraries (<see cref="JourneyDay"/>).
/// </summary>
/// <remarks>
/// Governs day-by-day scheduling, activity sequences, AI-generation lineage, and cost estimate snapshots.
/// Provides domain operations to add, remove, and reorder stops, as well as invariant validation.
/// </remarks>
public sealed class Journey : AggregateRoot
{
    private readonly List<JourneyDay> _days = new();
    private readonly List<CostEstimate> _costSnapshots = new();

    /// <summary>
    /// Gets the identifier of the linked parent trip, if associated.
    /// </summary>
    /// <value>The optional foreign key pointing to the <see cref="Trip"/>.</value>
    public Guid? TripId { get; private set; }

    /// <summary>
    /// Gets the title or name of the journey itinerary.
    /// </summary>
    /// <value>A descriptive title string.</value>
    public string Title { get; private set; } = string.Empty;

    /// <summary>
    /// Gets the total planned duration in days.
    /// </summary>
    /// <value>The positive integer day count.</value>
    public int TotalDays { get; private set; }

    /// <summary>
    /// Gets a value indicating whether this journey itinerary was synthesized by the AI assistant.
    /// </summary>
    /// <value><see langword="true"/> if generated by AI; otherwise, <see langword="false"/>.</value>
    public bool GeneratedByAI { get; private set; }

    /// <summary>
    /// Gets the current planning or execution status of the journey.
    /// </summary>
    /// <value>A <see cref="JourneyStatus"/> value.</value>
    public JourneyStatus Status { get; private set; } = JourneyStatus.Draft;

    /// <summary>
    /// Gets the collection of daily itineraries composing the journey.
    /// </summary>
    /// <value>An ordered, read-only collection of <see cref="JourneyDay"/> entities.</value>
    public IReadOnlyCollection<JourneyDay> Days => _days.OrderBy(d => d.DayNumber).ToList().AsReadOnly();

    /// <summary>
    /// Gets historical cost estimate calculation snapshots taken for this journey.
    /// </summary>
    /// <value>A read-only collection of <see cref="CostEstimate"/> snapshots.</value>
    public IReadOnlyCollection<CostEstimate> CostSnapshots => _costSnapshots.AsReadOnly();

    private Journey()
    {
    }

    private Journey(string title, int totalDays, bool generatedByAI, Guid? tripId = null)
    {
        Title = title;
        TotalDays = Math.Max(1, totalDays);
        GeneratedByAI = generatedByAI;
        TripId = tripId;
        Status = JourneyStatus.Draft;

        for (int i = 1; i <= TotalDays; i++)
        {
            _days.Add(JourneyDay.Create(Id, i));
        }
    }

    /// <summary>
    /// Factory method to construct a new <see cref="Journey"/> aggregate root.
    /// </summary>
    /// <param name="title">Descriptive title of the itinerary.</param>
    /// <param name="totalDays">Total number of itinerary days (must be at least 1).</param>
    /// <param name="generatedByAI">Whether this journey was synthesized by AI.</param>
    /// <param name="tripId">Optional identifier of the parent trip.</param>
    /// <returns>A new <see cref="Journey"/> aggregate initialized with sequential days.</returns>
    public static Journey Create(string title, int totalDays, bool generatedByAI = false, Guid? tripId = null) =>
        new(title ?? string.Empty, totalDays, generatedByAI, tripId);

    /// <summary>
    /// Adds a destination stop to a specified day in the journey.
    /// </summary>
    /// <param name="dayNumber">The 1-based day number to which the item is added.</param>
    /// <param name="destinationId">The catalog destination identifier.</param>
    /// <param name="cityId">Optional city identifier.</param>
    /// <param name="startTime">Optional scheduled start time.</param>
    /// <param name="endTime">Optional scheduled end time.</param>
    /// <param name="transport">Mode of transportation to the stop.</param>
    /// <returns>The created <see cref="JourneyItem"/>.</returns>
    /// <exception cref="InvalidOperationException">Thrown when <paramref name="dayNumber"/> does not exist.</exception>
    public JourneyItem AddItem(
        int dayNumber,
        Guid destinationId,
        int? cityId = null,
        TimeSpan? startTime = null,
        TimeSpan? endTime = null,
        TransportMode transport = TransportMode.Walking)
    {
        var day = _days.FirstOrDefault(d => d.DayNumber == dayNumber);
        if (day is null)
        {
            day = JourneyDay.Create(Id, dayNumber);
            _days.Add(day);
            if (dayNumber > TotalDays)
            {
                TotalDays = dayNumber;
            }
        }

        return day.AddItem(destinationId, cityId, startTime, endTime, transport);
    }

    /// <summary>
    /// Removes a destination stop item from any day in the journey.
    /// </summary>
    /// <param name="itemId">The identifier of the item to remove.</param>
    /// <returns><see langword="true"/> if the item was found and removed; otherwise, <see langword="false"/>.</returns>
    public bool RemoveItem(Guid itemId)
    {
        foreach (var day in _days)
        {
            if (day.RemoveItem(itemId))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Moves a destination stop item from its current day and position to a target day and order.
    /// </summary>
    /// <param name="itemId">The identifier of the item to move.</param>
    /// <param name="targetDayNumber">The destination day number.</param>
    /// <param name="newOrder">The desired sequence index in the target day.</param>
    /// <returns><see langword="true"/> if successfully relocated; otherwise, <see langword="false"/>.</returns>
    /// <exception cref="InvalidOperationException">Thrown when the target day does not exist.</exception>
    public bool MoveItem(Guid itemId, int targetDayNumber, int newOrder)
    {
        JourneyItem? foundItem = null;
        foreach (var day in _days)
        {
            var item = day.Items.FirstOrDefault(i => i.Id == itemId);
            if (item is not null)
            {
                foundItem = item;
                day.RemoveItem(itemId);
                break;
            }
        }

        if (foundItem is null)
        {
            return false;
        }

        var targetDay = _days.FirstOrDefault(d => d.DayNumber == targetDayNumber);
        if (targetDay is null)
        {
            targetDay = JourneyDay.Create(Id, targetDayNumber);
            _days.Add(targetDay);
            if (targetDayNumber > TotalDays)
            {
                TotalDays = targetDayNumber;
            }
        }

        targetDay.InsertItem(foundItem, newOrder);
        return true;
    }

    /// <summary>
    /// Validates business invariants across the journey itinerary.
    /// </summary>
    /// <remarks>
    /// Verifies that total days is positive, title is specified, all days are present,
    /// and that item scheduling windows (start time before end time) are valid.
    /// </remarks>
    /// <returns>A <see cref="ValidationResult"/> detailing whether the journey is valid and any invariant violations.</returns>
    public ValidationResult Validate()
    {
        var errors = new List<string>();

        if (string.IsNullOrWhiteSpace(Title))
        {
            errors.Add("Journey must have a valid non-empty title.");
        }

        if (TotalDays < 1)
        {
            errors.Add("Journey must span at least 1 day.");
        }

        if (_days.Count == 0)
        {
            errors.Add("Journey must contain at least one itinerary day.");
        }

        foreach (var day in _days)
        {
            foreach (var item in day.Items)
            {
                if (item.StartTime.HasValue && item.EndTime.HasValue && item.EndTime < item.StartTime)
                {
                    errors.Add($"Day {day.DayNumber} stop has an end time earlier than its start time.");
                }
            }
        }

        return errors.Count == 0
            ? ValidationResult.Success()
            : ValidationResult.Failure(errors);
    }

    /// <summary>
    /// Transitions the journey to a new status.
    /// </summary>
    /// <param name="status">The target <see cref="JourneyStatus"/>.</param>
    public void ChangeStatus(JourneyStatus status)
    {
        Status = status;
    }

    /// <summary>
    /// Records a calculated cost estimate snapshot for this journey.
    /// </summary>
    /// <param name="estimate">The calculated cost estimate snapshot.</param>
    public void RecordCostSnapshot(CostEstimate estimate)
    {
        ArgumentNullException.ThrowIfNull(estimate);
        _costSnapshots.Add(estimate);
    }

    /// <summary>
    /// Updates the journey's title.
    /// </summary>
    /// <param name="title">The revised title string.</param>
    public void UpdateTitle(string title)
    {
        Title = title ?? string.Empty;
    }
}

