using Voyara.Domain.ValueObjects;
using Voyara.SharedKernel.Results;

namespace Voyara.Domain.Entities.Moderation;

/// <summary>
/// An append-only record of something an admin did, kept for accountability (the design requires every admin
/// action and every report resolution to be written here). An entry is created once and never changed: every
/// property has a private setter and there are no behaviors that modify it.
/// </summary>
/// <remarks>
/// It deliberately does not use the platform's audit base class. It is itself the audit trail, so a
/// soft-delete flag or an "updated" timestamp would contradict append-only, and the design gives it a
/// <c>long</c> identifier generated by the database, which the Guid-based entity base cannot hold. The target
/// is stored as text because an entry may refer to any kind of object in any module.
/// </remarks>
public sealed class AuditLog
{
    /// <summary>Maximum length of the action.</summary>
    public const int MaxActionLength = 100;

    /// <summary>Maximum length of the target type.</summary>
    public const int MaxTargetTypeLength = 50;

    /// <summary>Maximum length of the target id.</summary>
    public const int MaxTargetIdLength = 50;

    /// <summary>Sequential identifier generated by the database; zero until the entry is saved.</summary>
    public long Id { get; private set; }

    /// <summary>Identifier of the admin who performed the action (reference to the Identity module).</summary>
    public Guid ActorId { get; private set; }

    /// <summary>What was done, for example "ReviewHidden".</summary>
    public string Action { get; private set; } = string.Empty;

    /// <summary>The kind of object affected, for example "Review".</summary>
    public string TargetType { get; private set; } = string.Empty;

    /// <summary>The identifier of the affected object, as text.</summary>
    public string TargetId { get; private set; } = string.Empty;

    /// <summary>When the action happened (UTC).</summary>
    public DateTimeOffset Timestamp { get; private set; }

    /// <summary>Extra details about the action: a JSON object (the diagram's DetailsJson is <c>Details.Json</c>).</summary>
    public AuditDetails Details { get; private set; } = null!;

    private AuditLog()
    {
    }

    private AuditLog(Guid actorId, string action, string targetType, string targetId, AuditDetails details)
    {
        ActorId = actorId;
        Action = action;
        TargetType = targetType;
        TargetId = targetId;
        Timestamp = DateTimeOffset.UtcNow;
        Details = details;
    }

    /// <summary>Creates a new audit entry after validating its values.</summary>
    /// <param name="actorId">The admin who performed the action.</param>
    /// <param name="action">What was done (required).</param>
    /// <param name="targetType">The kind of object affected (required).</param>
    /// <param name="targetId">The id of the affected object (required).</param>
    /// <param name="detailsJson">Optional JSON object with extra details; defaults to an empty object.</param>
    /// <returns>The new entry, or the first rule that was broken.</returns>
    public static Result<AuditLog> Create(
        Guid actorId, string action, string targetType, string targetId, string? detailsJson = null)
    {
        if (actorId == Guid.Empty)
        {
            return Result.Failure<AuditLog>(AuditLogErrors.ActorRequired);
        }

        if (string.IsNullOrWhiteSpace(action))
        {
            return Result.Failure<AuditLog>(AuditLogErrors.ActionRequired);
        }

        var trimmedAction = action.Trim();
        if (trimmedAction.Length > MaxActionLength)
        {
            return Result.Failure<AuditLog>(AuditLogErrors.ActionTooLong);
        }

        if (string.IsNullOrWhiteSpace(targetType))
        {
            return Result.Failure<AuditLog>(AuditLogErrors.TargetTypeRequired);
        }

        var trimmedTargetType = targetType.Trim();
        if (trimmedTargetType.Length > MaxTargetTypeLength)
        {
            return Result.Failure<AuditLog>(AuditLogErrors.TargetTypeTooLong);
        }

        if (string.IsNullOrWhiteSpace(targetId))
        {
            return Result.Failure<AuditLog>(AuditLogErrors.TargetIdRequired);
        }

        var trimmedTargetId = targetId.Trim();
        if (trimmedTargetId.Length > MaxTargetIdLength)
        {
            return Result.Failure<AuditLog>(AuditLogErrors.TargetIdTooLong);
        }

        var detailsResult = AuditDetails.Create(detailsJson);
        if (detailsResult.IsFailure)
        {
            return Result.Failure<AuditLog>(detailsResult.Error);
        }

        return new AuditLog(actorId, trimmedAction, trimmedTargetType, trimmedTargetId, detailsResult.Value);
    }
}