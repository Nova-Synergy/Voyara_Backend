using Voyara.Domain.Enums;

namespace Voyara.Domain.Entities.AiAssistant;

/// <summary>
/// Represents a single conversational turn (prompt, assistant completion, or system instruction) within an AI chat session.
/// </summary>
public sealed class Message
{
    /// <summary>
    /// Gets the unique 64-bit integer identifier of the message.
    /// </summary>
    /// <value>The database-generated primary key.</value>
    public long Id { get; private set; }

    /// <summary>
    /// Gets the identifier of the parent conversation aggregate.
    /// </summary>
    /// <value>The foreign key pointing to the owning <see cref="Conversation"/>.</value>
    public Guid ConversationId { get; private set; }

    /// <summary>
    /// Gets the authoring role of the message (User, Assistant, or System).
    /// </summary>
    /// <value>The <see cref="MessageRole"/> assigned to this message.</value>
    public MessageRole Role { get; private set; }

    /// <summary>
    /// Gets the textual content of the message.
    /// </summary>
    /// <value>The string content payload.</value>
    public string Content { get; private set; } = string.Empty;

    /// <summary>
    /// Gets the number of tokens consumed or generated by this specific message.
    /// </summary>
    /// <value>The non-negative count of tokens used.</value>
    public int TokensUsed { get; private set; }

    /// <summary>
    /// Gets the UTC timestamp when the message was sent or received.
    /// </summary>
    /// <value>The creation date and time in UTC.</value>
    public DateTime CreatedAt { get; private set; }

    private Message()
    {
    }

    private Message(Guid conversationId, MessageRole role, string content, int tokensUsed)
    {
        ConversationId = conversationId;
        Role = role;
        Content = content;
        TokensUsed = Math.Max(0, tokensUsed);
        CreatedAt = DateTime.UtcNow;
    }

    /// <summary>
    /// Factory method to create a new conversational <see cref="Message"/>.
    /// </summary>
    /// <param name="conversationId">The identifier of the conversation owning this message.</param>
    /// <param name="role">The authoring role of the message.</param>
    /// <param name="content">The textual message content.</param>
    /// <param name="tokensUsed">The token count associated with this turn.</param>
    /// <returns>A new <see cref="Message"/> instance.</returns>
    public static Message Create(Guid conversationId, MessageRole role, string content, int tokensUsed = 0)
    {
        return new Message(
            conversationId,
            role,
            content ?? string.Empty,
            tokensUsed);
    }
}

