using Voyara.Domain.Entities.Identity;

namespace Voyara.Domain.Entities.AiAssistant;

/// <summary>
/// Represents an operational telemetry log recording individual AI model invocations, token utilization, and estimated cost.
/// </summary>
/// <remarks>
/// Used for monitoring LLM consumption, performance latency, quota attribution, and financial billing per user and feature.
/// </remarks>
public sealed class AIUsageLog
{
    /// <summary>
    /// Gets the unique 64-bit integer identifier of the log entry.
    /// </summary>
    /// <value>The database-generated primary key.</value>
    public long Id { get; private set; }

    /// <summary>
    /// Gets the application feature or capability that initiated the AI request (e.g., "TripPlanning", "ImageAnalysis").
    /// </summary>
    /// <value>A descriptive string denoting the source feature.</value>
    public string Feature { get; private set; } = string.Empty;

    /// <summary>
    /// Gets the specific AI model identifier employed (e.g., "gemini-1.5-pro", "gemini-1.5-flash").
    /// </summary>
    /// <value>The machine-readable model name.</value>
    public string Model { get; private set; } = string.Empty;

    /// <summary>
    /// Gets the number of prompt/input tokens consumed by the request.
    /// </summary>
    /// <value>The non-negative count of input tokens.</value>
    public int InputTokens { get; private set; }

    /// <summary>
    /// Gets the number of completion/output tokens generated by the AI model.
    /// </summary>
    /// <value>The non-negative count of output tokens.</value>
    public int OutputTokens { get; private set; }

    /// <summary>
    /// Gets the estimated monetary cost incurred by this specific model invocation.
    /// </summary>
    /// <value>The calculated cost in USD.</value>
    public decimal Cost { get; private set; }

    /// <summary>
    /// Gets the round-trip latency of the AI service invocation in milliseconds.
    /// </summary>
    /// <value>The execution duration in milliseconds.</value>
    public int LatencyMs { get; private set; }

    /// <summary>
    /// Gets a value indicating whether the AI request completed successfully.
    /// </summary>
    /// <value><see langword="true"/> if the call succeeded; otherwise, <see langword="false"/>.</value>
    public bool Success { get; private set; }

    /// <summary>
    /// Gets the identifier of the user who triggered the AI feature.
    /// </summary>
    /// <value>The <see cref="Guid"/> foreign key of the calling user.</value>
    public Guid UserId { get; private set; }

    /// <summary>
    /// Gets the navigation reference to the user who triggered the request.
    /// </summary>
    /// <value>The owning <see cref="User"/> entity.</value>
    public User? User { get; private set; }

    /// <summary>
    /// Gets the UTC timestamp when the invocation occurred.
    /// </summary>
    /// <value>The date and time of the log entry.</value>
    public DateTime CreatedAt { get; private set; }

    private AIUsageLog()
    {
    }

    private AIUsageLog(
        Guid userId, string feature, string model,int inputTokens, int outputTokens,
        decimal cost, int latencyMs, bool success)
    {
        UserId = userId;
        Feature = feature;
        Model = model;
        InputTokens = Math.Max(0, inputTokens);
        OutputTokens = Math.Max(0, outputTokens);
        Cost = Math.Max(0m, cost);
        LatencyMs = Math.Max(0, latencyMs);
        Success = success;
        CreatedAt = DateTime.UtcNow;
    }

    /// <summary>
    /// Factory method to construct a new <see cref="AIUsageLog"/> record.
    /// </summary>
    /// <param name="userId">The identifier of the user triggering the feature.</param>
    /// <param name="feature">The feature or domain component calling the model.</param>
    /// <param name="model">The model name or version identifier.</param>
    /// <param name="inputTokens">The count of input prompt tokens.</param>
    /// <param name="outputTokens">The count of generated response tokens.</param>
    /// <param name="cost">The monetary expense incurred.</param>
    /// <param name="latencyMs">The elapsed invocation time in milliseconds.</param>
    /// <param name="success">Whether the invocation completed successfully.</param>
    /// <returns>A new <see cref="AIUsageLog"/> instance with UTC timestamp.</returns>
    public static AIUsageLog Create(
        Guid userId, string feature,string model, int inputTokens,
        int outputTokens, decimal cost,int latencyMs,bool success)
    {
        return new AIUsageLog(
            userId,
            feature ?? string.Empty,
            model ?? string.Empty,
            inputTokens,
            outputTokens,
            cost,
            latencyMs,
            success);
    }
}
